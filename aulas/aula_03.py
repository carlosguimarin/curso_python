"""
Python = Linguagemrde programação
Tipo de tipagem = Dinâmica / Forte
str -> string -> texto
Strings são textos que estão dentro de aspas
"""
print(1234) # int -> inteiro

# Aspas simples
print('Olá, mundo')
print('Olá, "mundo"')

# Aspas duplas
print("Olá, mundo")
print("Olá, 'mundo'")

# Escape
print("Olá, \"mundo\"")

# r
print(r"Olá, \"mundo\"")