"""
Exercício 1: Cálculo de Bônus de Vendas (RH/Vendas):
Uma empresa decidiu dar um bônus de 10% sobre o faturamento total
para a equipe de vendas. Calcule o valor do bônus e o faturamento final
da empresa após subtrair esse bônus.

Faturamento inicial: 50.000
Percentual de bônus: 0.10

"""

faturamentototal = 50000
bonus = faturamentototal * 0.10
faturamentofinal = faturamentototal - bonus

print(f'O valor do bônus é igual a:  {bonus}')
print(f'O faturamento final é igual a:  {faturamentofinal}')