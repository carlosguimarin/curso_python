name = 'Carlos Marin'
height = 1.75
weight = 92
bmi = weight / (height ** 2)

line_1 = f'{name} has {height:.2f} of height'
line_2 = f'weighs {weight} kilograms'
line_3 = f'and his BMI is {bmi:.2f}'

print(line_1)
print(line_2)
print(line_3)

# Carlos Marin has 1.75 height,
# weighs 92 kilograms and his BMI is 30.04